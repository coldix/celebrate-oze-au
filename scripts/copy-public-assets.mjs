#!/usr/bin/env node
/*
    File: /scripts/copy-public-assets.mjs
    Website: celebrate.oze.au
    Description: Mirror the repo-root asset folders into public/ before a build.
                 css/, js/, images/ and the shirley90 media stay at the root so
                 the Hostinger rollback path keeps working, and Astro only ships
                 what is in public/.
    Author: Colin Dixon + Claude Opus 5
*/
import { cpSync, mkdirSync, existsSync, rmSync, readdirSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const pub = join(root, 'public');
mkdirSync(pub, { recursive: true });

// Astro generates every .html page. The Python helpers are local-only tooling
// that the Hostinger workflow already refuses to publish; keep them out here too.
const SKIP_EXT = new Set(['.html', '.py']);

const copyTree = (from, to) => {
  mkdirSync(to, { recursive: true });
  for (const entry of readdirSync(from)) {
    if (entry.startsWith('.')) continue; // .DS_Store and friends never ship
    const src = join(from, entry);
    const dst = join(to, entry);
    if (statSync(src).isDirectory()) {
      copyTree(src, dst);
    } else if (!SKIP_EXT.has(extname(entry))) {
      cpSync(src, dst);
    }
  }
};

for (const dir of ['css', 'js', 'images', 'shirley90', 'legal']) {
  const src = join(root, dir);
  if (!existsSync(src)) continue;
  const dst = join(pub, dir);
  // Wipe first: cpSync only adds and overwrites, so a deleted source file
  // would otherwise linger in public/ and keep shipping.
  rmSync(dst, { recursive: true, force: true });
  copyTree(src, dst);
  console.log(`Copied ${dir}/ -> public/${dir}/ (html and py skipped)`);
}

// sitemap.xml is deliberately absent: the root one lists the .html addresses
// Hostinger serves, while the Worker's is generated by src/pages/sitemap.xml.ts.
for (const f of ['_headers', 'favicon.ico', 'apple-touch-icon.png', 'robots.txt', 'llms.txt']) {
  const src = join(root, f);
  if (existsSync(src)) cpSync(src, join(pub, f));
}
